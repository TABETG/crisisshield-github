import { useParams, Link } from 'react-router-dom';
import { Package, Download, ArrowLeft } from 'lucide-react';
import { useEmergencyKit } from '../api';
import { LoadingSpinner, Button, Badge } from '../shared/components';
import { formatDate, formatFileSize } from '../shared/utils/formatters';
import { EmergencyKitStatus } from '../types';

export const EmergencyKitDetailPage = () => {
  const { kitId } = useParams<{ kitId: string }>();
  const { data: kit, isLoading } = useEmergencyKit(kitId!);

  const getStatusBadge = (status: EmergencyKitStatus) => {
    const variants = {
      [EmergencyKitStatus.READY]: 'success' as const,
      [EmergencyKitStatus.GENERATING]: 'info' as const,
      [EmergencyKitStatus.EXPIRED]: 'warning' as const,
      [EmergencyKitStatus.FAILED]: 'danger' as const,
    };
    return <Badge variant={variants[status]}>{status}</Badge>;
  };

  if (isLoading) return <LoadingSpinner />;
  if (!kit) return <div className="text-center py-12"><p className="text-gray-600">Kit not found</p></div>;

  return (
    <div>
      <Link to="/emergency/kits" className="inline-flex items-center text-sm text-gray-600 hover:text-gray-900 mb-4"><ArrowLeft className="w-4 h-4 mr-1" />Back to kits</Link>
      <div className="bg-white rounded-lg shadow-sm border border-gray-200 p-6">
        <div className="flex items-start justify-between mb-6">
          <div className="flex items-start">
            <Package className="w-8 h-8 text-blue-600 mr-3 mt-1" />
            <div>
              <h1 className="text-2xl font-bold text-gray-900">{kit.name}</h1>
              <div className="mt-2">{getStatusBadge(kit.status)}</div>
            </div>
          </div>
          {kit.status === EmergencyKitStatus.READY && kit.downloadUrl && (
            <a href={kit.downloadUrl} download><Button><Download className="w-4 h-4 mr-2" />Download Kit</Button></a>
          )}
        </div>

        <div className="grid grid-cols-2 gap-6 mt-6 pt-6 border-t border-gray-200">
          <div><p className="text-sm font-medium text-gray-500">Generated</p><p className="mt-1 text-sm text-gray-900">{formatDate(kit.generatedAt)}</p></div>
          <div><p className="text-sm font-medium text-gray-500">Generated By</p><p className="mt-1 text-sm text-gray-900">{kit.createdBy}</p></div>
          {kit.expiresAt && <div><p className="text-sm font-medium text-gray-500">Expires</p><p className="mt-1 text-sm text-gray-900">{formatDate(kit.expiresAt)}</p></div>}
          {kit.fileSize && <div><p className="text-sm font-medium text-gray-500">File Size</p><p className="mt-1 text-sm text-gray-900">{formatFileSize(kit.fileSize)}</p></div>}
        </div>

        {kit.includedPlans.length > 0 && (
          <div className="mt-6 pt-6 border-t border-gray-200">
            <h3 className="text-sm font-medium text-gray-900 mb-2">Included Plans</h3>
            <ul className="list-disc list-inside text-sm text-gray-600">{kit.includedPlans.map((p, i) => <li key={i}>{p}</li>)}</ul>
          </div>
        )}
      </div>
    </div>
  );
};
